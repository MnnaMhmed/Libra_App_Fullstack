import express from "express";
import cors from "cors";
import helmet from "helmet";
import morgan from "morgan";
import rateLimit from "express-rate-limit";
import swaggerUi from "swagger-ui-express";
import { env } from "./config/env.js";
import { authenticate } from "./middleware/auth.js";
import { errorHandler, notFound } from "./middleware/errorHandler.js";
import authRoutes from "./routes/auth.routes.js";
import booksRoutes from "./routes/books.routes.js";
import borrowingRoutes from "./routes/borrowing.routes.js";
import usersRoutes from "./routes/users.routes.js";
import profileRoutes from "./routes/profile.routes.js";
import wishlistRoutes from "./routes/wishlist.routes.js";
import dashboardRoutes from "./routes/dashboard.routes.js";
import activityRoutes from "./routes/activity.routes.js";
import { resourceRouter } from "./routes/resource.routes.js";
import { memberSchema, authorSchema, publisherSchema, categorySchema } from "./validation/schemas.js";
import { openApiDocument } from "./docs/openapi.js";

const app = express();
app.use(helmet());
app.use(cors({ origin: env.clientOrigin.split(",").map(x => x.trim()), credentials: true }));
app.use(express.json({ limit: "2mb" }));
app.use(express.urlencoded({ extended: true }));
app.use(morgan(env.nodeEnv === "production" ? "combined" : "dev"));
app.use("/api", rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: "draft-8", legacyHeaders: false }));
app.get("/health", (req, res) => res.json({ success: true, message: "Libra API is running." }));
app.use("/api/docs", swaggerUi.serve, swaggerUi.setup(openApiDocument));
app.use("/api/auth", authRoutes);
app.use("/api", authenticate);
app.use("/api/dashboard", dashboardRoutes);
app.use("/api/books", booksRoutes);
app.use("/api/members", resourceRouter("members", memberSchema));
app.use("/api/authors", resourceRouter("authors", authorSchema));
app.use("/api/publishers", resourceRouter("publishers", publisherSchema));
app.use("/api/categories", resourceRouter("categories", categorySchema));
app.use("/api/borrowings", borrowingRoutes);
app.use("/api/users", usersRoutes);
app.use("/api/activity-logs", activityRoutes);
app.use("/api/profile", profileRoutes);
app.use("/api/wishlist", wishlistRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
